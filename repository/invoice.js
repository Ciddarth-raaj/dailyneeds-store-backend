  // Get invoice with items by ID
  getInvoiceWithItems(invoiceId) {
    return new Promise((resolve, reject) => {
      this.db.query(
        `SELECT i.*, 
                ii.invoice_item_id, ii.product_id, ii.quantity, ii.cost, ii.discount, 
                ii.tax, ii.tax_amount, ii.markup_percentage, ii.final_selling_price, 
                ii.puom, ii.suom, ii.created_at as item_created_at, ii.updated_at as item_updated_at
         FROM invoice i
         LEFT JOIN invoice_items ii ON i.invoice_id = ii.invoice_id
         WHERE i.invoice_id = ?`,
        [invoiceId],
        (err, results) => {
          if (err) {
            logger.Log({
              level: logger.LEVEL.ERROR,
              component: "REPOSITORY.INVOICE",
              code: "REPOSITORY.INVOICE.GET_WITH_ITEMS",
              description: err.toString(),
              category: "",
              ref: {},
            });
            reject(err);
            return;
          }

          if (results.length === 0) {
            resolve({ code: 404, msg: "Invoice not found" });
            return;
          }

          // Structure the response
          const invoice = {
            invoice_id: results[0].invoice_id,
            created_at: results[0].created_at,
            updated_at: results[0].updated_at,
            invoice_items: [],
          };

          results.forEach((row) => {
            if (row.invoice_item_id) {
              invoice.invoice_items.push({
                invoice_item_id: row.invoice_item_id,
                product_id: row.product_id,
                quantity: row.quantity,
                cost: row.cost,
                discount: row.discount,
                tax: row.tax,
                tax_amount: row.tax_amount,
                markup_percentage: row.markup_percentage,
                final_selling_price: row.final_selling_price,
                puom: row.puom,
                suom: row.suom,
                created_at: row.item_created_at,
                updated_at: row.item_updated_at,
              });
            }
          });

          resolve({ code: 200, data: invoice });
        }
      );
    });
  }

