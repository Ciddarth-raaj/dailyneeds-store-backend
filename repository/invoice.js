  // Create invoice with items in a single transaction
  createInvoiceWithItems(invoiceData) {
    return new Promise((resolve, reject) => {
      this.db.getConnection((err, connection) => {
        if (err) {
          logger.Log({
            level: logger.LEVEL.ERROR,
            component: "REPOSITORY.INVOICE",
            code: "REPOSITORY.INVOICE.GET_CONNECTION",
            description: err.toString(),
            category: "",
            ref: {},
          });
          return reject(err);
        }

        connection.beginTransaction(async (err) => {
          if (err) {
            connection.release();
            logger.Log({
              level: logger.LEVEL.ERROR,
              component: "REPOSITORY.INVOICE",
              code: "REPOSITORY.INVOICE.CREATE_TRANSACTION",
              description: err.toString(),
              category: "",
              ref: {},
            });
            return reject(err);
          }

          try {
            // Create invoice
            const invoiceResult = await this.createInvoiceWithConnection(
              connection,
              invoiceData
            );
            if (invoiceResult.code !== 200) {
              throw new Error("Failed to create invoice");
            }

            const invoiceId = invoiceResult.id;

            // Create invoice items
            if (
              invoiceData.invoice_items &&
              invoiceData.invoice_items.length > 0
            ) {
              for (const item of invoiceData.invoice_items) {
                item.invoice_id = invoiceId;
                const itemResult = await this.createInvoiceItemWithConnection(
                  connection,
                  item
                );
                if (itemResult.code !== 200) {
                  throw new Error("Failed to create invoice item");
                }
              }
            }

            // Commit transaction
            connection.commit((err) => {
              if (err) {
                return connection.rollback(() => {
                  connection.release();
                  logger.Log({
                    level: logger.LEVEL.ERROR,
                    component: "REPOSITORY.INVOICE",
                    code: "REPOSITORY.INVOICE.COMMIT",
                    description: err.toString(),
                    category: "",
                    ref: {},
                  });
                  reject(err);
                });
              }
              connection.release();
              resolve({ code: 200, id: invoiceId });
            });
          } catch (error) {
            connection.rollback(() => {
              connection.release();
              logger.Log({
                level: logger.LEVEL.ERROR,
                component: "REPOSITORY.INVOICE",
                code: "REPOSITORY.INVOICE.CREATE_WITH_ITEMS",
                description: error.toString(),
                category: "",
                ref: {},
              });
              reject(error);
            });
          }
        });
      });
    });
  }

